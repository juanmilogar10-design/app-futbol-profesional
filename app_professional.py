# 4️⃣ Función para calcular promedios de goles por equipo
def calcular_promedios(df):
    equipos = pd.concat([df["home_team"], df["away_team"]]).unique()
    data = {}
    for equipo in equipos:
        local = df[df["home_team"] == equipo]
        visitante = df[df["away_team"] == equipo]

        goles_anotados = local["fulltime_home"].sum() + visitante["fulltime_away"].sum()
        goles_recibidos = local["fulltime_away"].sum() + visitante["fulltime_home"].sum()
        partidos = local.shape[0] + visitante.shape[0]

        media_anotados = goles_anotados / partidos if partidos > 0 else 0
        media_recibidos = goles_recibidos / partidos if partidos > 0 else 0

        data[equipo] = {"gf": media_anotados, "gc": media_recibidos}
    return data

promedios = calcular_promedios(df_ligas)

# 5️⃣ Función para predecir resultado con Poisson
def predecir_poisson(local, visitante, promedios):
    lambda_local = promedios[local]["gf"]
    lambda_visitante = promedios[visitante]["gf"]

    # Probabilidades básicas 0-5 goles
    max_goles = 5
    prob_local = [poisson.pmf(i, lambda_local) for i in range(max_goles+1)]
    prob_visitante = [poisson.pmf(i, lambda_visitante) for i in range(max_goles+1)]

    # Probabilidades de 1X2
    prob_1 = sum([prob_local[i]*sum(prob_visitante[j] for j in range(i)) for i in range(max_goles+1)])
    prob_X = sum([prob_local[i]*prob_visitante[i] for i in range(max_goles+1)])
    prob_2 = sum([sum(prob_local[i] for i in range(j)) * prob_visitante[j] for j in range(max_goles+1)])

    # Probabilidad de Over/Under 2.5
    over_2_5 = 1 - sum([prob_local[i]*prob_visitante[j] for i in range(max_goles+1) for j in range(max_goles+1) if i+j <=2])
    under_2_5 = 1 - over_2_5

    # Ambos marcan (BTTS)
    btts = 1 - (prob_local[0]*sum(prob_visitante) + prob_visitante[0]*sum(prob_local))

    return {
        "1": round(prob_1*100,1),
        "X": round(prob_X*100,1),
        "2": round(prob_2*100,1),
        "Over2.5": round(over_2_5*100,1),
        "Under2.5": round(under_2_5*100,1),
        "BTTS": round(btts*100,1)
    }

