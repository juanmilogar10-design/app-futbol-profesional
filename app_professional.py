    """
    Predice ganador, Over/Under 0.5,1.5,2.5 y BTTS
    usando promedios históricos de la liga.
    """
    equipo_local = df_liga[df_liga["Equipo"] == local]
    equipo_visita = df_liga[df_liga["Equipo"] == visitante]

    # Si alguno no tiene datos, devolver vacíos
    if equipo_local.empty or equipo_visita.empty:
        return pd.Series({
            "Local": local,
            "Visitante": visitante,
            "Predicción Ganador": "ND",
            "Over 0.5": "ND",
            "Over 1.5": "ND",
            "Over 2.5": "ND",
            "BTTS": "ND"
        })

    # Promedio goles anotados y recibidos
    goles_local = equipo_local["Promedio goles"].values[0]
    goles_visita = equipo_visita["Promedio goles"].values[0]

    # Ganador simple
    if goles_local > goles_visita:
        ganador = "Local"
    elif goles_visita > goles_local:
        ganador = "Visitante"
    else:
        ganador = "Empate"

    # Over/Under 0.5,1.5,2.5
    over_05 = "Sí" if goles_local + goles_visita > 0.5 else "No"
    over_15 = "Sí" if goles_local + goles_visita > 1.5 else "No"
    over_25 = "Sí" if goles_local + goles_visita > 2.5 else "No"

    # Ambos marcan (BTTS)
    btts = "Sí" if (equipo_local["Goles anotados"].values[0] > 0 and equipo_visita["Goles anotados"].values[0] > 0) else "No"

    return pd.Series({
        "Local": local,
        "Visitante": visitante,
        "Predicción Ganador": ganador,
        "Over 0.5": over_05,
        "Over 1.5": over_15,
        "Over 2.5": over_25,
        "BTTS": btts
    })

